def main():
    out = []
    for image, topic, question, options, ans_letter, qtype in DATA:
        out.append({
            "image": image,
            "topic": topic,
            "kind": "question",
            "questions": [{
                "question": question,
                "options": options,
                "answer": [ch for ch in ans_letter],
                "type": qtype,
                "has_redbox": True,
                "confidence": "high",
            }],
            "note": "",
        })
    out_path = os.path.join(BASE, 'scripts', '_image_questions.json')
    with open(out_path, 'w', encoding='utf-8') as f:
        json.dump(out, f, ensure_ascii=False, indent=2)
    nq = sum(len(x['questions']) for x in out)
    print(f'图片数: {len(out)}  题目数: {nq}')
    from collections import Counter
    types = Counter(q['type'] for x in out for q in x['questions'])
    print(f'题型分布: {dict(types)}')
    print(f'全部有红框答案: {all(q["has_redbox"] for x in out for q in x["questions"])}')
    print(f'Written -> {out_path}')


if __name__ == '__main__':
    main()
